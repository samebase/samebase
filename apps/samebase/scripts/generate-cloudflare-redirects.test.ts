import { readFileSync } from "node:fs";
import { describe, expect, it } from "vite-plus/test";

import {
  createCloudflarePrerenderRedirectsBlock,
  GENERATED_REDIRECTS_END_TAG,
  GENERATED_REDIRECTS_START_TAG,
  replaceGeneratedCloudflareRedirectsBlock,
} from "./generate-cloudflare-redirects.js";
import { createPrerenderPathRewrites, type PublicPrerenderPage } from "../prerenderPaths.js";

const expectedMetadata = {
  title: "Test page | Samebase",
  description: "Test page metadata.",
  robots: "noindex,nofollow",
} satisfies PublicPrerenderPage["expectedMetadata"];

const pages = [
  {
    path: "/",
    expectedMetadata,
    prerender: {
      enabled: true,
      outputPath: "/_landing.html",
    },
  },
  {
    path: "/terms",
    expectedMetadata,
    prerender: {
      enabled: true,
    },
  },
] satisfies PublicPrerenderPage[];
const prerenderPathRewrites = createPrerenderPathRewrites(pages);
const cloudflareRedirects = readFileSync(new URL("../public/_redirects", import.meta.url), "utf8");

describe("generate-cloudflare-redirects", () => {
  it("redirects retired landing paths before the SPA fallback", () => {
    expect(cloudflareRedirects).toContain(
      [
        "/landing-preview / 301",
        "/landing-preview/ / 301",
        "/landing-preview/index.html / 301",
      ].join("\n"),
    );
  });

  it("temporarily redirects retired home paths to the vault", () => {
    expect(cloudflareRedirects).toContain(
      ["/home /vault/ 302", "/home/ /vault/ 302", "/home/index.html /vault/ 302"].join("\n"),
    );
  });

  it("creates exact aliases from public prerender pages", () => {
    expect(createCloudflarePrerenderRedirectsBlock(prerenderPathRewrites)).toBe(
      [
        "# Generated by pnpm run generate:cloudflare-redirects.",
        "# Cloudflare SPA mode serves /index.html for unknown app routes, so",
        "# the SPA shell owns that file. These exact aliases expose prerendered",
        "# public pages without catching hashed assets.",
        "",
        "/ /_landing.html 200",
        "",
        "/terms /terms/index.html 200",
        "/terms/ /terms/index.html 200",
        "/terms/index.html /terms/index.html 200",
      ].join("\n"),
    );
  });

  it("replaces only the tagged generated block", () => {
    const contents = [
      "# custom exact redirects can live before the generated block",
      "/favicon.ico /favicon.png 200",
      "",
      GENERATED_REDIRECTS_START_TAG,
      "/old /old.html 200",
      GENERATED_REDIRECTS_END_TAG,
      "",
      "/support /support.html 200",
      "",
    ].join("\n");

    expect(
      replaceGeneratedCloudflareRedirectsBlock({
        contents,
        generatedBlock: createCloudflarePrerenderRedirectsBlock(prerenderPathRewrites),
      }),
    ).toBe(
      [
        "# custom exact redirects can live before the generated block",
        "/favicon.ico /favicon.png 200",
        "",
        GENERATED_REDIRECTS_START_TAG,
        "# Generated by pnpm run generate:cloudflare-redirects.",
        "# Cloudflare SPA mode serves /index.html for unknown app routes, so",
        "# the SPA shell owns that file. These exact aliases expose prerendered",
        "# public pages without catching hashed assets.",
        "",
        "/ /_landing.html 200",
        "",
        "/terms /terms/index.html 200",
        "/terms/ /terms/index.html 200",
        "/terms/index.html /terms/index.html 200",
        GENERATED_REDIRECTS_END_TAG,
        "",
        "/support /support.html 200",
        "",
      ].join("\n"),
    );
  });

  it("requires the generated block tags", () => {
    expect(() =>
      replaceGeneratedCloudflareRedirectsBlock({
        contents: "/favicon.ico /favicon.png 200\n",
        generatedBlock: createCloudflarePrerenderRedirectsBlock(prerenderPathRewrites),
      }),
    ).toThrow(`Missing ${GENERATED_REDIRECTS_START_TAG}`);
  });

  it("keeps prerender pages from taking the Cloudflare SPA shell path", () => {
    const workerSsrRootPage = {
      path: "/",
      expectedMetadata,
      prerender: {
        enabled: true,
        outputPath: "/index.html",
      },
    } satisfies PublicPrerenderPage;

    expect(() => createPrerenderPathRewrites([workerSsrRootPage])).toThrow(
      "SPA shell serves that file",
    );
  });
});
