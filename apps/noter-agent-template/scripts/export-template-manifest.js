import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const baseDir = path.resolve(__dirname, "..");

const EXCLUDED_TOP_LEVEL_DIRS = new Set([
  "node_modules",
  "dist",
  "scripts",
  ".git",
]);
const EXCLUDED_FILENAMES = new Set(["seed-manifest.json"]);
const BINARY_EXTENSIONS = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".ico",
  ".pdf",
  ".zip",
  ".tar",
  ".gz",
  ".tgz",
  ".bz2",
  ".7z",
  ".woff",
  ".woff2",
  ".ttf",
  ".otf",
  ".mp4",
  ".mov",
  ".mp3",
  ".wav",
]);

const isHiddenEntry = name => name.startsWith(".");

const isBinaryBuffer = buffer => {
  const sampleSize = Math.min(buffer.length, 8000);
  for (let i = 0; i < sampleSize; i += 1) {
    if (buffer[i] === 0) {
      return true;
    }
  }
  return false;
};

async function collectFiles(rootDir, currentDir, depth) {
  const entries = await readdir(currentDir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    if (isHiddenEntry(entry.name)) {
      continue;
    }

    const absolutePath = path.join(currentDir, entry.name);
    const relativePath = path
      .relative(rootDir, absolutePath)
      .split(path.sep)
      .join("/");

    if (
      depth === 0 &&
      entry.isDirectory() &&
      EXCLUDED_TOP_LEVEL_DIRS.has(entry.name)
    ) {
      continue;
    }

    if (entry.isFile() && EXCLUDED_FILENAMES.has(entry.name)) {
      continue;
    }

    if (entry.isDirectory()) {
      files.push(...(await collectFiles(rootDir, absolutePath, depth + 1)));
      continue;
    }

    if (!entry.isFile()) {
      continue;
    }

    const extension = path.extname(relativePath).toLowerCase();
    if (BINARY_EXTENSIONS.has(extension)) {
      continue;
    }

    const contentBuffer = await readFile(absolutePath);
    if (isBinaryBuffer(contentBuffer)) {
      continue;
    }

    const content = contentBuffer.toString("utf8");
    files.push({ relativePath, content });
  }

  return files;
}

const files = await collectFiles(baseDir, baseDir, 0);
files.sort((left, right) =>
  left.relativePath.localeCompare(right.relativePath),
);

if (files.length === 0) {
  throw new Error("Template export found no files");
}

const manifest = {
  version: "agent-template-0.0.0",
  commitMessage: "chore: seed agent template",
  files: Object.fromEntries(
    files.map(file => [file.relativePath, file.content]),
  ),
};

const outputPath = path.resolve(
  baseDir,
  "../noter/convex/agentSeedManifest.generated.ts",
);
const generated = `// @generated by apps/noter-agent-template/scripts/export-template-manifest.js\n\nexport type AgentTemplateManifest = {\n  version: string;\n  commitMessage: string;\n  files: Record<string, string>;\n};\n\nexport const agentTemplateManifest: AgentTemplateManifest = ${JSON.stringify(
  manifest,
  null,
  2,
)};\n`;

await writeFile(outputPath, generated, "utf8");
console.log(`wrote ${outputPath}`);
