import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { syncCodespaceAssets } from "./sync-codespace-assets.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const baseDir = path.resolve(__dirname, "..");

const EXCLUDED_TOP_LEVEL_DIRS = new Set([
  "node_modules",
  "dist",
  ".turbo",
  "scripts",
  "seed-commits",
]);
const EXCLUDED_FILENAMES = new Set(["seed-manifest.json"]);

/** @typedef {{ relativePath: string; content: string }} CollectedFile */

/**
 * @param {string} rootDir
 * @param {string} currentDir
 * @param {number} depth
 * @returns {Promise<CollectedFile[]>}
 */
async function collectFiles(rootDir, currentDir, depth) {
  const entries = await readdir(currentDir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = path.join(currentDir, entry.name);
    const relativePath = path
      .relative(rootDir, absolutePath)
      .split(path.sep)
      .join("/");

    if (
      depth === 0 &&
      entry.isDirectory() &&
      EXCLUDED_TOP_LEVEL_DIRS.has(entry.name)
    ) {
      continue;
    }

    if (entry.isFile() && EXCLUDED_FILENAMES.has(entry.name)) {
      continue;
    }

    if (entry.isDirectory()) {
      files.push(...(await collectFiles(rootDir, absolutePath, depth + 1)));
      continue;
    }

    if (!entry.isFile()) {
      continue;
    }

    const content = await readFile(absolutePath, "utf8");
    files.push({ relativePath, content });
  }

  return files;
}

const packageJsonPath = path.join(baseDir, "package.json");
const packageJsonRaw = await readFile(packageJsonPath, "utf8");
const packageJson = JSON.parse(packageJsonRaw);
const packageVersion =
  typeof packageJson.version === "string" ? packageJson.version : "0.0.0";

await syncCodespaceAssets();

const files = await collectFiles(baseDir, baseDir, 0);
files.sort((left, right) =>
  left.relativePath.localeCompare(right.relativePath),
);

if (files.length === 0) {
  throw new Error("Template export found no files");
}

const manifest = {
  version: `starter-template-${packageVersion}`,
  commitMessage: "chore: seed starter template",
  files: Object.fromEntries(
    files.map((file) => [file.relativePath, file.content]),
  ),
};

const outputPath = path.resolve(
  baseDir,
  "../noter/convex/starterSeedManifest.generated.ts",
);
const generated = `// @generated by apps/noter-starter-template/scripts/export-template-manifest.mjs\n\nexport type StarterTemplateManifest = {\n  version: string;\n  commitMessage: string;\n  files: Record<string, string>;\n};\n\nexport const starterTemplateManifest: StarterTemplateManifest = ${JSON.stringify(
  manifest,
  null,
  2,
)};\n`;

await writeFile(outputPath, generated, "utf8");
console.log(`wrote ${outputPath}`);
