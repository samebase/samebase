#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

import { isMainModule, resolveRepoRoot, runMain } from "./lib/scriptRuntime.ts";

export const trackedFilePathsOutputPath = "scripts/generated/trackedFilePaths.generated.ts";

function compareUtf8PathBytes(left: string, right: string): number {
  // Compare bytes, not locale collation, so generated order is stable across
  // Node runtimes and ICU builds.
  return Buffer.compare(Buffer.from(left, "utf8"), Buffer.from(right, "utf8"));
}

function isGeneratedOutputPath(filePath: string): boolean {
  return filePath === trackedFilePathsOutputPath;
}

export function parseGitTrackedFilePaths(gitLsFilesOutput: Buffer): string[] {
  const filePaths = gitLsFilesOutput
    .toString("utf8")
    .split("\0")
    .filter((filePath) => filePath.length > 0);

  const uniqueFilePaths = new Set<string>();
  for (const filePath of filePaths) {
    if (path.isAbsolute(filePath) || filePath.includes("\\")) {
      throw new Error(`Git returned an unsupported tracked path: ${filePath}`);
    }
    if (!isGeneratedOutputPath(filePath)) {
      uniqueFilePaths.add(filePath);
    }
  }

  return [...uniqueFilePaths].sort(compareUtf8PathBytes);
}

export function assertTrackedFilePathsExist(repoRoot: string, filePaths: readonly string[]): void {
  for (const filePath of filePaths) {
    if (!existsSync(path.join(repoRoot, filePath))) {
      throw new Error(`Tracked file path is missing from the working tree: ${filePath}`);
    }
  }
}

export function formatTrackedFilePathsSource(filePaths: readonly string[]): string {
  if (filePaths.length === 0) {
    throw new Error("Cannot generate tracked file path types from an empty file list.");
  }

  const pathLines = filePaths.map((filePath) => `  ${JSON.stringify(filePath)},`).join("\n");

  return `// @generated by scripts/generate-tracked-file-paths.ts
// Do not edit by hand. Run \`pnpm run generate:tracked-file-paths\`.

export const trackedFilePaths = [
${pathLines}
] as const;

export type TrackedFilePath = (typeof trackedFilePaths)[number];
`;
}

export function readTrackedFilePaths(repoRoot: string): string[] {
  const filePaths = parseGitTrackedFilePaths(
    execFileSync("git", ["ls-files", "-z", "--cached"], {
      cwd: repoRoot,
    }),
  );
  assertTrackedFilePathsExist(repoRoot, filePaths);
  return filePaths;
}

export function writeTrackedFilePathsGeneratedFile(repoRoot: string): void {
  const outputFilePath = path.join(repoRoot, trackedFilePathsOutputPath);
  mkdirSync(path.dirname(outputFilePath), { recursive: true });
  writeFileSync(
    outputFilePath,
    formatTrackedFilePathsSource(readTrackedFilePaths(repoRoot)),
    "utf8",
  );
}

if (isMainModule(import.meta.url)) {
  await runMain(() => writeTrackedFilePathsGeneratedFile(resolveRepoRoot()));
}
