import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, expect, it } from "vite-plus/test";

import {
  assertTrackedFilePathsExist,
  formatTrackedFilePathsSource,
  parseGitTrackedFilePaths,
  readTrackedFilePaths,
  trackedFilePathsOutputPath,
} from "./generate-tracked-file-paths.ts";

describe("generate-tracked-file-paths", () => {
  it("parses sorted git-tracked paths and excludes the generated output file", () => {
    const input = Buffer.from(
      [
        "scripts/run-context-dev.ts",
        trackedFilePathsOutputPath,
        "apps/noter/package.json",
        "",
      ].join("\0"),
    );

    expect(parseGitTrackedFilePaths(input)).toEqual([
      "apps/noter/package.json",
      "scripts/run-context-dev.ts",
    ]);
  });

  it("formats a generated const array and derived type from tracked paths", () => {
    expect(formatTrackedFilePathsSource(["a.ts", "nested/file.ts"]))
      .toBe(`// @generated by scripts/generate-tracked-file-paths.ts
// Do not edit by hand. Run \`pnpm run generate:tracked-file-paths\`.

export const trackedFilePaths = [
  "a.ts",
  "nested/file.ts",
] as const;

export type TrackedFilePath = (typeof trackedFilePaths)[number];
`);
  });

  it("rejects absolute paths from git output", () => {
    expect(() => parseGitTrackedFilePaths(Buffer.from("/tmp/file.ts\0"))).toThrow(
      "unsupported tracked path",
    );
  });

  it("rejects tracked paths that are missing from the working tree", () => {
    expect(() =>
      assertTrackedFilePathsExist(process.cwd(), ["missing-file-for-path-type-test.ts"]),
    ).toThrow("missing from the working tree");
  });

  it("ignores untracked files in the working tree", () => {
    const repoRoot = mkdtempSync(path.join(tmpdir(), "tracked-file-paths-test-"));

    try {
      execFileSync("git", ["init"], { cwd: repoRoot });
      writeFileSync(path.join(repoRoot, "tracked.ts"), "", "utf8");
      mkdirSync(path.join(repoRoot, "scratch"));
      writeFileSync(path.join(repoRoot, "scratch", "untracked.ts"), "", "utf8");
      execFileSync("git", ["add", "tracked.ts"], { cwd: repoRoot });

      expect(readTrackedFilePaths(repoRoot)).toEqual(["tracked.ts"]);
    } finally {
      rmSync(repoRoot, { recursive: true, force: true });
    }
  });
});
