import path from "node:path";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { describe, expect, it } from "vite-plus/test";
import {
  buildPlaywrightCliConfig,
  buildDerivedSessionName,
  ensurePlaywrightCliConfig,
  getDeterministicBrowserThemeColor,
  getPlaywrightCliConfigPath,
  getPlaywrightCliChromiumArgs,
  parseProfileBrowserProcessesFromPsOutput,
  parseSessionDetailsFromListOutput,
  parseSessionStateFromListOutput,
  sanitizeChromeCrashRecoveryState,
} from "./playwright-branch-browser.ts";

describe("playwright-branch-browser", () => {
  it("pins crash suppression and a deterministic worktree theme in the repo-owned cli config", () => {
    expect(
      buildPlaywrightCliConfig("/Users/nicu/.codex/worktrees/0fb0/noter"),
    ).toEqual({
      browser: {
        browserName: "chromium",
        launchOptions: {
          channel: "chromium",
          args: [
            "--disable-session-crashed-bubble",
            "--install-autogenerated-theme=71,215,160",
          ],
        },
      },
    });
  });

  it("writes the config into the repo-local playwright metadata directory", () => {
    const repoRoot = mkdtempSync(path.join(tmpdir(), "noter-playwright-cli-"));
    const configPath = ensurePlaywrightCliConfig(repoRoot);

    expect(configPath).toBe(getPlaywrightCliConfigPath(repoRoot));
    expect(JSON.parse(readFileSync(configPath, "utf8"))).toEqual(
      buildPlaywrightCliConfig(repoRoot),
    );
  });

  it("shortens derived session names so they fit local socket path limits", () => {
    expect(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/0fb0/noter",
        "codex/disable-restore-pages-prompt",
      ),
    ).toBe("noter-drp-e06cfa");
  });

  it("derives different branch sessions for different worktree roots", () => {
    expect(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/0fb0/noter",
        "codex/disable-restore-pages-prompt",
      ),
    ).not.toBe(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/1234/noter",
        "codex/disable-restore-pages-prompt",
      ),
    );
  });

  it("derives a stable browser color from the worktree root", () => {
    expect(
      getDeterministicBrowserThemeColor(
        "/Users/nicu/.codex/worktrees/0fb0/noter",
      ),
    ).toEqual({
      red: 71,
      green: 215,
      blue: 160,
    });
    expect(
      getPlaywrightCliChromiumArgs("/Users/nicu/.codex/worktrees/0fb0/noter"),
    ).toEqual([
      "--disable-session-crashed-bubble",
      "--install-autogenerated-theme=71,215,160",
    ]);
    expect(
      getDeterministicBrowserThemeColor(
        "/Users/nicu/.codex/worktrees/1234/noter",
      ),
    ).not.toEqual(
      getDeterministicBrowserThemeColor(
        "/Users/nicu/.codex/worktrees/0fb0/noter",
      ),
    );
  });

  it("clears persisted crash markers before relaunching a persistent profile", () => {
    const profileDir = mkdtempSync(
      path.join(tmpdir(), "noter-chrome-profile-"),
    );
    const defaultDir = path.join(profileDir, "Default");

    mkdirSync(defaultDir, { recursive: true });
    writeFileSync(
      path.join(profileDir, "Local State"),
      JSON.stringify({ variations_crash_streak: 4 }),
    );
    writeFileSync(
      path.join(profileDir, "Variations"),
      JSON.stringify({
        "user_experience_metrics.stability.exited_cleanly": false,
        variations_crash_streak: 2,
      }),
    );
    writeFileSync(
      path.join(defaultDir, "Preferences"),
      JSON.stringify({
        profile: { exit_type: "Crashed" },
        sessions: {
          event_log: [
            { crashed: true, time: "1", type: 0 },
            { crashed: false, time: "2", type: 0 },
          ],
        },
      }),
    );

    sanitizeChromeCrashRecoveryState(profileDir);

    expect(
      JSON.parse(readFileSync(path.join(profileDir, "Local State"), "utf8")),
    ).toEqual({ variations_crash_streak: 0 });
    expect(
      JSON.parse(readFileSync(path.join(profileDir, "Variations"), "utf8")),
    ).toEqual({
      "user_experience_metrics.stability.exited_cleanly": true,
      variations_crash_streak: 0,
    });
    expect(
      JSON.parse(readFileSync(path.join(defaultDir, "Preferences"), "utf8")),
    ).toEqual({
      profile: { exit_type: "Normal" },
      sessions: {
        event_log: [
          { crashed: false, time: "1", type: 0 },
          { crashed: false, time: "2", type: 0 },
        ],
      },
    });
  });

  it("tolerates malformed crash-state JSON from an unclean browser exit", () => {
    const profileDir = mkdtempSync(
      path.join(tmpdir(), "noter-chrome-profile-"),
    );
    const defaultDir = path.join(profileDir, "Default");

    mkdirSync(defaultDir, { recursive: true });
    writeFileSync(path.join(profileDir, "Local State"), '{"broken":');
    writeFileSync(path.join(profileDir, "Variations"), "{");
    writeFileSync(path.join(defaultDir, "Preferences"), "not-json");

    expect(() => sanitizeChromeCrashRecoveryState(profileDir)).not.toThrow();
    expect(
      JSON.parse(readFileSync(path.join(profileDir, "Local State"), "utf8")),
    ).toEqual({ variations_crash_streak: 0 });
    expect(
      JSON.parse(readFileSync(path.join(profileDir, "Variations"), "utf8")),
    ).toEqual({
      "user_experience_metrics.stability.exited_cleanly": true,
      variations_crash_streak: 0,
    });
    expect(
      JSON.parse(readFileSync(path.join(defaultDir, "Preferences"), "utf8")),
    ).toEqual({});
  });

  it("distinguishes open sessions from closed remembered sessions", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- noter-drp-e06cfa:",
      "  - status: closed",
      "  - browser-type: chromium",
      "  - user-data-dir: /tmp/noter-drp-e06cfa",
      "  - headed: false",
      "- restore-smoke:",
      "  - status: open",
      "  - browser-type: chrome",
      "  - user-data-dir: /tmp/restore-smoke",
      "  - headed: true",
    ].join("\n");

    expect(
      parseSessionStateFromListOutput(sampleOutput, "noter-drp-e06cfa"),
    ).toBe("closed");
    expect(parseSessionStateFromListOutput(sampleOutput, "restore-smoke")).toBe(
      "open",
    );
    expect(
      parseSessionStateFromListOutput(sampleOutput, "missing-session"),
    ).toBe("missing");
  });

  it("parses session browser details from playwright-cli list output", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- noter-drp-e06cfa:",
      "  - status: open",
      "  - browser-type: chromium",
      "  - user-data-dir: /tmp/noter-drp-e06cfa",
      "  - headed: true",
    ].join("\n");

    expect(
      parseSessionDetailsFromListOutput(sampleOutput, "noter-drp-e06cfa"),
    ).toEqual({
      status: "open",
      browserType: "chromium",
      userDataDir: "/tmp/noter-drp-e06cfa",
      headed: true,
    });
  });

  it("matches only true top-level session headers", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- restore-smoke:",
      "  - status: open",
      "  - browser-type: chromium",
      "- status:",
      "  - status: closed",
      "  - browser-type: chrome",
    ].join("\n");

    expect(parseSessionStateFromListOutput(sampleOutput, "status")).toBe(
      "closed",
    );
    expect(
      parseSessionDetailsFromListOutput(sampleOutput, "restore-smoke"),
    ).toEqual({
      status: "open",
      browserType: "chromium",
    });
  });

  it("matches only exact user-data-dir process arguments", () => {
    const sampleOutput = [
      "41763 /tmp/chromium --user-data-dir=/tmp/noter-drp-e06cfa --flag",
      "41764 /tmp/chromium --user-data-dir=/tmp/noter-drp-e06cfax --flag",
      "41765 /tmp/chromium --profile-directory=Default --user-data-dir=/tmp/noter-drp-e06cfa",
    ].join("\n");

    expect(
      parseProfileBrowserProcessesFromPsOutput(
        sampleOutput,
        "/tmp/noter-drp-e06cfa",
      ),
    ).toEqual([
      {
        pid: 41763,
        args: "/tmp/chromium --user-data-dir=/tmp/noter-drp-e06cfa --flag",
      },
      {
        pid: 41765,
        args: "/tmp/chromium --profile-directory=Default --user-data-dir=/tmp/noter-drp-e06cfa",
      },
    ]);
  });
});
