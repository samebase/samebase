import path from "node:path";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { describe, expect, it } from "vite-plus/test";
import {
  buildPlaywrightCliConfig,
  buildDerivedSessionName,
  ensurePlaywrightCliConfig,
  getDeterministicBrowserThemeColor,
  getPlaywrightCliConfigPath,
  getPlaywrightCliChromiumArgs,
  parseProfileBrowserProcessesFromPsOutput,
  parseSessionDetailsFromListOutput,
  parseSessionStateFromListOutput,
  sanitizeChromeCrashRecoveryState,
} from "./playwright-branch-browser.ts";

describe("playwright-branch-browser", () => {
  it("pins crash suppression and a deterministic worktree theme in the repo-owned cli config", () => {
    expect(buildPlaywrightCliConfig("/Users/nicu/.codex/worktrees/0fb0/samebase")).toEqual({
      browser: {
        browserName: "chromium",
        launchOptions: {
          channel: "chromium",
          args: ["--disable-session-crashed-bubble", "--install-autogenerated-theme=71,215,160"],
        },
      },
    });
  });

  it("writes the config into the repo-local playwright metadata directory", () => {
    const repoRoot = mkdtempSync(path.join(tmpdir(), "samebase-playwright-cli-"));
    const configPath = ensurePlaywrightCliConfig(repoRoot);

    expect(configPath).toBe(getPlaywrightCliConfigPath(repoRoot));
    expect(JSON.parse(readFileSync(configPath, "utf8"))).toEqual(
      buildPlaywrightCliConfig(repoRoot),
    );
  });

  it("shortens derived session names so they fit local socket path limits", () => {
    expect(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/0fb0/samebase",
        "codex/disable-restore-pages-prompt",
      ),
    ).toBe("sameb-drp-a08f36");
  });

  it("derives different branch sessions for different worktree roots", () => {
    expect(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/0fb0/samebase",
        "codex/disable-restore-pages-prompt",
      ),
    ).not.toBe(
      buildDerivedSessionName(
        "/Users/nicu/.codex/worktrees/1234/samebase",
        "codex/disable-restore-pages-prompt",
      ),
    );
  });

  it("derives a stable browser color from the worktree root", () => {
    expect(getDeterministicBrowserThemeColor("/Users/nicu/.codex/worktrees/0fb0/samebase")).toEqual(
      {
        red: 207,
        green: 71,
        blue: 215,
      },
    );
    expect(getPlaywrightCliChromiumArgs("/Users/nicu/.codex/worktrees/0fb0/samebase")).toEqual([
      "--disable-session-crashed-bubble",
      "--install-autogenerated-theme=207,71,215",
    ]);
    expect(
      getDeterministicBrowserThemeColor("/Users/nicu/.codex/worktrees/1234/samebase"),
    ).not.toEqual(getDeterministicBrowserThemeColor("/Users/nicu/.codex/worktrees/0fb0/samebase"));
  });

  it("clears persisted crash markers before relaunching a persistent profile", () => {
    const profileDir = mkdtempSync(path.join(tmpdir(), "samebase-chrome-profile-"));
    const defaultDir = path.join(profileDir, "Default");

    mkdirSync(defaultDir, { recursive: true });
    writeFileSync(
      path.join(profileDir, "Local State"),
      JSON.stringify({ variations_crash_streak: 4 }),
    );
    writeFileSync(
      path.join(profileDir, "Variations"),
      JSON.stringify({
        "user_experience_metrics.stability.exited_cleanly": false,
        variations_crash_streak: 2,
      }),
    );
    writeFileSync(
      path.join(defaultDir, "Preferences"),
      JSON.stringify({
        profile: { exit_type: "Crashed" },
        sessions: {
          event_log: [
            { crashed: true, time: "1", type: 0 },
            { crashed: false, time: "2", type: 0 },
          ],
        },
      }),
    );

    sanitizeChromeCrashRecoveryState(profileDir);

    expect(JSON.parse(readFileSync(path.join(profileDir, "Local State"), "utf8"))).toEqual({
      variations_crash_streak: 0,
    });
    expect(JSON.parse(readFileSync(path.join(profileDir, "Variations"), "utf8"))).toEqual({
      "user_experience_metrics.stability.exited_cleanly": true,
      variations_crash_streak: 0,
    });
    expect(JSON.parse(readFileSync(path.join(defaultDir, "Preferences"), "utf8"))).toEqual({
      profile: { exit_type: "Normal" },
      sessions: {
        event_log: [
          { crashed: false, time: "1", type: 0 },
          { crashed: false, time: "2", type: 0 },
        ],
      },
    });
  });

  it("tolerates malformed crash-state JSON from an unclean browser exit", () => {
    const profileDir = mkdtempSync(path.join(tmpdir(), "samebase-chrome-profile-"));
    const defaultDir = path.join(profileDir, "Default");

    mkdirSync(defaultDir, { recursive: true });
    writeFileSync(path.join(profileDir, "Local State"), '{"broken":');
    writeFileSync(path.join(profileDir, "Variations"), "{");
    writeFileSync(path.join(defaultDir, "Preferences"), "not-json");

    expect(() => sanitizeChromeCrashRecoveryState(profileDir)).not.toThrow();
    expect(JSON.parse(readFileSync(path.join(profileDir, "Local State"), "utf8"))).toEqual({
      variations_crash_streak: 0,
    });
    expect(JSON.parse(readFileSync(path.join(profileDir, "Variations"), "utf8"))).toEqual({
      "user_experience_metrics.stability.exited_cleanly": true,
      variations_crash_streak: 0,
    });
    expect(JSON.parse(readFileSync(path.join(defaultDir, "Preferences"), "utf8"))).toEqual({});
  });

  it("distinguishes open sessions from closed remembered sessions", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- sameb-drp-a08f36:",
      "  - status: closed",
      "  - browser-type: chromium",
      "  - user-data-dir: /tmp/sameb-drp-a08f36",
      "  - headed: false",
      "- restore-smoke:",
      "  - status: open",
      "  - browser-type: chrome",
      "  - user-data-dir: /tmp/restore-smoke",
      "  - headed: true",
    ].join("\n");

    expect(parseSessionStateFromListOutput(sampleOutput, "sameb-drp-a08f36")).toBe("closed");
    expect(parseSessionStateFromListOutput(sampleOutput, "restore-smoke")).toBe("open");
    expect(parseSessionStateFromListOutput(sampleOutput, "missing-session")).toBe("missing");
  });

  it("parses session browser details from playwright-cli list output", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- sameb-drp-a08f36:",
      "  - status: open",
      "  - browser-type: chromium",
      "  - user-data-dir: /tmp/sameb-drp-a08f36",
      "  - headed: true",
    ].join("\n");

    expect(parseSessionDetailsFromListOutput(sampleOutput, "sameb-drp-a08f36")).toEqual({
      status: "open",
      browserType: "chromium",
      userDataDir: "/tmp/sameb-drp-a08f36",
      headed: true,
    });
  });

  it("matches only true top-level session headers", () => {
    const sampleOutput = [
      "57814cf9b7521b5a:",
      "- restore-smoke:",
      "  - status: open",
      "  - browser-type: chromium",
      "- status:",
      "  - status: closed",
      "  - browser-type: chrome",
    ].join("\n");

    expect(parseSessionStateFromListOutput(sampleOutput, "status")).toBe("closed");
    expect(parseSessionDetailsFromListOutput(sampleOutput, "restore-smoke")).toEqual({
      status: "open",
      browserType: "chromium",
    });
  });

  it("matches only exact user-data-dir process arguments", () => {
    const sampleOutput = [
      "41763 /tmp/chromium --user-data-dir=/tmp/sameb-drp-a08f36 --flag",
      "41764 /tmp/chromium --user-data-dir=/tmp/sameb-drp-a08f36x --flag",
      "41765 /tmp/chromium --profile-directory=Default --user-data-dir=/tmp/sameb-drp-a08f36",
    ].join("\n");

    expect(parseProfileBrowserProcessesFromPsOutput(sampleOutput, "/tmp/sameb-drp-a08f36")).toEqual(
      [
        {
          pid: 41763,
          args: "/tmp/chromium --user-data-dir=/tmp/sameb-drp-a08f36 --flag",
        },
        {
          pid: 41765,
          args: "/tmp/chromium --profile-directory=Default --user-data-dir=/tmp/sameb-drp-a08f36",
        },
      ],
    );
  });
});
